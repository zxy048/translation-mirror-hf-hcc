# -*- coding: utf-8 -*-
"""
Rebuild the PLOS ONE v2 submission package from source.

WHY THIS FILE EXISTS
--------------------
The v2 package was assembled by hand on 2026-10-04. Only two of its six upload
files had a script behind them (`build_plos_docx_v2.py` for the manuscript,
`build_tracked_docx.py` for the tracked revision); the cover letter and the
response letter were pandoc'd ad hoc and the figures and SI PDF were copied by
hand. So a change to a title in the markdown had no path to the package, and the
package could not be rebuilt from the repository at all.

That is the same failure this repository was rebuilt to eliminate: an artifact in
a submission with no reproducible source. The first submission shipped a
supplementary PDF that no script in the repository could produce, and it turned
out to be from an abandoned analysis. A package you cannot rebuild is a package
you cannot check.

Run this after editing any of the four source documents. It rebuilds all four
docx and copies in the figures and SI PDF, which are generated by the R pipeline
(`R17_figures.R`, `R19_build_SI_pdf.py`) and are checked here by hash rather than
regenerated.

Usage:  python assemble_plos_v2.py
"""
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import zlib

ROOT = r"D:\R_projects\revision_analysis"
PKG = os.path.join(ROOT, "PLOS_ONE_Submission_v2")

# The manuscript number and the letter's date both come from the decision email
# and from nowhere else. Typing either into the letter means two places to get
# it wrong, and the number is the one field the submission system is guaranteed
# to check. The template carries tokens; this file carries the values; an
# internal build substitutes whatever is there, while a submission build
# (PLOS_SUBMISSION=1) refuses to run while a token survives.
CONFIG = os.path.join(ROOT, "submission_config.json")
COVER_MD = os.path.join(ROOT, "Cover_Letter_PLOSONE_v2.md")
TOKENS = {
    "manuscript_id": "{{MANUSCRIPT_ID}}",
    "submission_date": "{{SUBMISSION_DATE}}",
}


def load_config():
    with open(CONFIG, encoding="utf-8") as fh:
        return json.load(fh)


def unfilled(cfg):
    """Keys whose configured value is still the token itself (or empty)."""
    return [k for k, tok in TOKENS.items()
            if str(cfg.get(k, "")).strip() in ("", tok)]


def substitute(text, cfg):
    for key, tok in TOKENS.items():
        text = text.replace(tok, str(cfg.get(key, tok)))
    return text

# Document sources -> the numbered name they are uploaded under.
# (source, destination, builder) where builder is "pandoc" or a script path.
DOCS = [
    (os.path.join(ROOT, "Manuscript_PLOSONE_v2.md"),
     "03_Manuscript.docx", "build_plos_docx_v2.py"),
    (None,  # produced by build_tracked_docx.py, has no markdown of its own
     "04_Revised_Manuscript_with_Track_Changes.docx", "build_tracked_docx.py"),
    (os.path.join(ROOT, "Cover_Letter_PLOSONE_v2.md"),
     "01_Cover_Letter.docx", "pandoc"),
    (os.path.join(ROOT, "v2_output", "Response_to_Reviewers.md"),
     "02_Response_to_Reviewers.docx", "pandoc"),
]

# Copied rather than rebuilt. The source hash is asserted so that a stale or
# hand-edited package file cannot pass as current: the point of listing the
# expected source is to notice when the two have drifted apart.
#
# The Supporting Information is uploaded under the name of the caption that
# describes it. PLOS requires file names to match captions ("a PDF file for
# 'S2 Fig.' must be named 'S2_fig.pdf'"), and since the supplement is one
# consolidated file it is captioned S1 File -- so the name is S1_File.pdf, not
# a description of its contents. The earlier 05_Supporting_Information.pdf was
# a generic name that matched no caption the manuscript defines.
COPIES = [
    (os.path.join(ROOT, "v2_output", "Supporting_Information_v2.pdf"),
     "S1_File.pdf"),
]

# Rendered rather than copied. PLOS takes TIFF (or EPS) for figures, not PDF,
# so the three main figures are rasterised at 600 dpi by their own script. That
# script writes straight into the package, which is why these are listed
# separately from COPIES: there is no source file to hash, because the source
# is the vector PDF plus this render step. (source_pdf, package_name)
FIGURES = [
    ("Fig1_harmonised_networks.pdf", "Fig1.tiff"),
    ("Fig2_pathway_mirror.pdf", "Fig2.tiff"),
    ("Fig3_same_organ_controls.pdf", "Fig3.tiff"),
]

# Superseded upload names. Left in place they would ship alongside their
# replacements and the package would carry two versions of every figure -- one
# of them in a format PLOS does not accept, under a name no caption defines.
STALE = ["Fig1.pdf", "Fig2.pdf", "Fig3.pdf", "05_Supporting_Information.pdf"]

# Files in the package that are NOT upload items. Listed explicitly so that the
# assembly reports them rather than silently carrying them forward. There used
# to be a `Fig1.docx` here -- a scratch paste-up of the Fig 1 panels, one empty
# paragraph and two embedded images, never an upload item -- and it is deleted
# rather than carried, since nothing can regenerate it.
NOT_UPLOADED = ["00_提交清单_勿上传.md", "preview_png"]


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


# cairo stamps /CreationDate into every PDF it writes, so two renders of an
# unchanged figure are never byte-identical -- and the copy loop below duly
# reported UPDATED for every figure on every run, which is the same as
# reporting nothing. The stamp lives inside a Flate-compressed object stream
# rather than in the raw bytes, so normalising it means decompressing each
# stream before hashing it. Streams that do not decompress (the image data)
# are hashed as they are.
#
# The stream start is matched as `>> stream`, not as `stream` alone. A bare
# `stream\r?\n` occurs *inside* the compressed binary too -- 22 matches in a
# file with 11 streams -- and each false positive desynchronised the scan so
# that a real body was misread as raw bytes and hashed with its timestamp
# intact. That is the whole bug: the first version of this function still
# reported two identical renders as different, which is how it was caught.
_DATE = re.compile(rb"D:\d{14}[^)]*")
_STREAM = re.compile(rb">>\s*stream\r?\n")


def pdf_content_hash(path):
    """Hash a PDF's content, ignoring the render timestamp cairo writes."""
    with open(path, "rb") as fh:
        raw = fh.read()
    h = hashlib.sha256()
    pos = 0
    for m in re.finditer(_STREAM, raw):
        end = raw.find(b"endstream", m.end())
        if end < 0:
            break
        h.update(raw[pos:m.end()])
        chunk = raw[m.end():end]
        try:
            h.update(_DATE.sub(b"D:<date>", zlib.decompress(chunk)))
        except zlib.error:
            h.update(chunk)
        pos = end
    h.update(raw[pos:])
    return h.hexdigest()


def run(cmd, **kw):
    env = dict(os.environ, PYTHONIOENCODING="utf-8")
    p = subprocess.run(cmd, cwd=ROOT, env=env, **kw)
    if p.returncode != 0:
        sys.exit("FAILED: %s" % " ".join(cmd))


def pandoc_docx(src_md, dst_docx):
    """Markdown -> docx, matching the format the letters were shipped in.

    Deliberately plain: the letters in this package carry no explicit font,
    size or margin overrides, and adding `format_plos` here would silently
    re-typeset documents that have already been read by the authors. Change the
    formatting on purpose or not at all.
    """
    run(["pandoc", src_md, "-o", dst_docx,
         "--from", "markdown+superscript+subscript"])


def main():
    if not os.path.isdir(PKG):
        sys.exit("package directory not found: %s" % PKG)

    print("=" * 74)
    print("Rebuilding the four submission documents")
    print("=" * 74)

    for src, dst, builder in DOCS:
        print("\n[%s]" % dst)
        if builder == "pandoc":
            if not os.path.exists(src):
                sys.exit("  source missing: %s" % src)
            tmp = os.path.join(ROOT, "_pkg_tmp.docx")
            source = src
            if os.path.abspath(src) == os.path.abspath(COVER_MD):
                cfg = load_config()
                missing = unfilled(cfg)
                if missing and os.environ.get("PLOS_SUBMISSION") == "1":
                    sys.exit(
                        "submission build refused: %s still holds %s. Fill "
                        "%s from the decision email first."
                        % (os.path.basename(CONFIG),
                           ", ".join(TOKENS[k] for k in missing),
                           "them" if len(missing) > 1 else "it"))
                # Substitute into a temp source rather than editing the template:
                # the .md on disk must keep its tokens, or the next submission
                # inherits this one's manuscript number.
                source = os.path.join(ROOT, "_pkg_tmp.md")
                with open(src, encoding="utf-8") as fh:
                    body = fh.read()
                with open(source, "w", encoding="utf-8", newline="") as fh:
                    fh.write(substitute(body, cfg))
                if missing:
                    print("  note: internal build; %s left as placeholders"
                          % ", ".join(TOKENS[k] for k in missing))
            pandoc_docx(source, tmp)
            if source != src:
                os.remove(source)
            shutil.copy2(tmp, os.path.join(PKG, dst))
            os.remove(tmp)
            print("  pandoc %s -> %s" % (os.path.basename(src), dst))
        elif builder == "build_tracked_docx.py":
            run([sys.executable, builder])
            built = os.path.join(ROOT, "Manuscript_PLOSONE_v2_tracked.docx")
            shutil.copy2(built, os.path.join(PKG, dst))
            print("  %s -> %s" % (builder, dst))
        else:
            run([sys.executable, builder])
            built = os.path.join(ROOT, "Manuscript_PLOSONE_v2.docx")
            shutil.copy2(built, os.path.join(PKG, dst))
            print("  %s -> %s" % (builder, dst))

    print("\n" + "=" * 74)
    print("Dropping superseded upload files")
    print("=" * 74)
    for name in STALE:
        full = os.path.join(PKG, name)
        if os.path.exists(full):
            os.remove(full)
            print("  removed %s" % name)
        else:
            print("  %s absent (ok)" % name)

    print("\n" + "=" * 74)
    print("Rendering the three main figures as 600 dpi TIFF")
    print("=" * 74)
    run([sys.executable, "build_figure_tiffs.py"])

    print("\n" + "=" * 74)
    print("Copying the Supporting Information")
    print("=" * 74)
    for src, dst in COPIES:
        if not os.path.exists(src):
            sys.exit("  source missing: %s" % src)
        dst_path = os.path.join(PKG, dst)
        digest = pdf_content_hash if dst.lower().endswith(".pdf") else sha256
        same = os.path.exists(dst_path) and digest(src) == digest(dst_path)
        shutil.copy2(src, dst_path)
        print("  %-34s -> %-30s %s"
              % (os.path.relpath(src, ROOT), dst,
                 "unchanged" if same else "UPDATED"))

    # preview_png/ is for eyeballing the layout; it is never uploaded. It used to
    # be a hand-copied leftover and had drifted five days behind the figures it is
    # supposed to preview, which is the failure mode this whole script exists to
    # prevent -- an artifact in the package that no command can reproduce. It is
    # rebuilt here from the same PNGs the figures are rendered to, so a preview
    # and the figure it previews cannot disagree.
    prev = os.path.join(PKG, "preview_png")
    os.makedirs(prev, exist_ok=True)
    try:
        from PIL import Image
    except ImportError:
        print("  (Pillow not installed -- preview_png/ left as it was)")
    else:
        for src_pdf, dst in FIGURES:
            png = os.path.join(ROOT, "v2_output", "figures",
                               os.path.splitext(src_pdf)[0] + ".png")
            if not os.path.exists(png):
                continue
            im = Image.open(png)
            im = im.resize((1200, round(1200 * im.size[1] / im.size[0])), Image.LANCZOS)
            out = os.path.join(prev, os.path.splitext(dst)[0] + ".png")
            im.save(out)
            print("  preview %-27s -> %s" % (os.path.basename(png), os.path.relpath(out, ROOT)))

    print("\n" + "=" * 74)
    print("Package contents")
    print("=" * 74)
    for name in sorted(os.listdir(PKG)):
        full = os.path.join(PKG, name)
        if os.path.isdir(full):
            print("      %-46s (directory)" % name)
            continue
        note = "  <- do not upload" if name in NOT_UPLOADED else ""
        print("  %-46s %8d B%s" % (name, os.path.getsize(full), note))

    print("\nUpload these eight, and nothing else:")
    for name in ("01_Cover_Letter.docx", "02_Response_to_Reviewers.docx",
                 "03_Manuscript.docx",
                 "04_Revised_Manuscript_with_Track_Changes.docx",
                 "S1_File.pdf",
                 "Fig1.tiff  Fig2.tiff  Fig3.tiff"):
        print("  " + name)
    print("\nThen run: python verify_all.py")
    return 0


if __name__ == "__main__":
    sys.exit(main())
